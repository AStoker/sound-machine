const uint8_t *glyph(const Font &font, char c) {
  if (c >= 'a' && c <= 'z')
    c = static_cast<char>(c - 'a' + 'A');
  if (c >= '0' && c <= '9')
    return font.digits + (c - '0') * font.height;
  if (c >= 'A' && c <= 'Z')
    return font.alpha + (c - 'A') * font.height;
  const char *found = std::strchr(PUNCTUATION, c);
  // strchr finds the terminating NUL too, which is not a glyph.
  if (found != nullptr && c != '\0')
    return font.punct + (found - PUNCTUATION) * font.height;
  return nullptr;  // space / unknown -> blank
}

